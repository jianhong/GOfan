#' Sunburst Plot for Enriched Gene Ontology Terms
#'
#' GOfan provides a simple and intuitive way to visualize Gene Ontology (GO)
#' enrichment results using a sunburst layout inspired by SynGO. Unlike
#' graph-based or dot plot methods, it preserves hierarchical relationships
#' among GO terms while maintaining a clean, interpretable view. GOfan accepts
#' any enrichment results containing GO identifiers and uses color to represent
#' additional information such as p-values or gene counts, making GO analysis
#' both informative and visually engaging.
